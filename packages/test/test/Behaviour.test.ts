import { assert, describe, it } from "@effect/vitest"
import { type Explore, exploreGraph } from "@mufw/core"
import { Counter } from "../../core/test/fixtures/Counter.ts"
import { behaviourOf, blindSpots, renderBehaviour } from "../src/index.ts"

const graphOf = (explore: Explore<typeof Counter>) => exploreGraph(Counter, explore)

const everyProposal = graphOf(() => [{ _tag: "Inc", by: 1 }, { _tag: "Inc", by: 3 }, { _tag: "Reset" }])

describe("behaviourOf", () => {
  it("lists each sampled proposal with its target state and the fields that change", () => {
    assert.deepStrictEqual(behaviourOf(Counter, everyProposal), [
      {
        state: "low",
        controlState: "low",
        proposal: { tag: "Inc", payload: { by: 1 } },
        target: "low",
        targetControlState: "low",
        changed: ["count"]
      },
      {
        state: "low",
        controlState: "low",
        proposal: { tag: "Inc", payload: { by: 3 } },
        target: "high",
        targetControlState: "high",
        changed: ["count"]
      },
      {
        state: "low",
        controlState: "low",
        proposal: { tag: "Reset", payload: {} },
        target: "low",
        targetControlState: "low",
        changed: []
      },
      {
        state: "high",
        controlState: "high",
        proposal: { tag: "Inc", payload: { by: 1 } },
        target: "high",
        targetControlState: "high",
        changed: ["count"]
      },
      {
        state: "high",
        controlState: "high",
        proposal: { tag: "Inc", payload: { by: 3 } },
        target: "high",
        targetControlState: "high",
        changed: ["count"]
      },
      {
        state: "high",
        controlState: "high",
        proposal: { tag: "Reset", payload: {} },
        target: "low",
        targetControlState: "low",
        changed: ["count"]
      }
    ])
  })
})

describe("blindSpots", () => {
  it("reports nothing when every tag is sampled from every state and every field varies", () => {
    assert.deepStrictEqual(blindSpots(Counter, everyProposal), { untried: [], constant: [] })
  })

  it("reports a proposal tag the samples never use as untried in each state", () => {
    const onlyInc = graphOf(() => [{ _tag: "Inc", by: 3 }])

    assert.deepStrictEqual(blindSpots(Counter, onlyInc).untried, [
      { state: "low", tag: "Reset" },
      { state: "high", tag: "Reset" }
    ])
  })

  it("reports a model field with one encoded value across the explored states as constant", () => {
    const onlyReset = graphOf(() => [{ _tag: "Reset" }])

    assert.deepStrictEqual(blindSpots(Counter, onlyReset), {
      untried: [{ state: "low", tag: "Inc" }],
      constant: [{ field: "count", value: 0 }]
    })
  })

  it("reports a field that only transition results change as constant when every explored state stores one value", () => {
    const onlyIncByOne = graphOf(() => [{ _tag: "Inc", by: 1 }])

    assert.deepStrictEqual(blindSpots(Counter, onlyIncByOne), {
      untried: [{ state: "low", tag: "Reset" }],
      constant: [{ field: "count", value: 0 }]
    })
  })
})

describe("renderBehaviour", () => {
  it("renders one table per state and the blind spots, with a self-loop showing no field change", () => {
    assert.strictEqual(
      renderBehaviour(Counter, everyProposal),
      [
        "# Behaviour of counter",
        "",
        "> Generated by `renderBehaviour` from the explore samples of `counter`; `vitest -u` rewrites it. " +
        "It shows only the proposals exploration sampled, applied to the model each explored state stores.",
        "",
        "## low [low]",
        "",
        "| proposal | → state | fields that change |",
        "| --- | --- | --- |",
        "| `Inc {\"by\":1}` | low [low] | count |",
        "| `Inc {\"by\":3}` | high [high] | count |",
        "| `Reset` | low [low] | — |",
        "",
        "## high [high]",
        "",
        "| proposal | → state | fields that change |",
        "| --- | --- | --- |",
        "| `Inc {\"by\":1}` | high [high] | count |",
        "| `Inc {\"by\":3}` | high [high] | count |",
        "| `Reset` | low [low] | count |",
        "",
        "## Blind spots",
        "",
        "### Untried proposals",
        "",
        "none",
        "",
        "### Fields with one value in every explored state",
        "",
        "none",
        ""
      ].join("\n")
    )
  })

  it("lists untried pairs and constant fields in the blind spots", () => {
    const onlyReset = graphOf(() => [{ _tag: "Reset" }])

    assert.strictEqual(
      renderBehaviour(Counter, onlyReset),
      [
        "# Behaviour of counter",
        "",
        "> Generated by `renderBehaviour` from the explore samples of `counter`; `vitest -u` rewrites it. " +
        "It shows only the proposals exploration sampled, applied to the model each explored state stores.",
        "",
        "## low [low]",
        "",
        "| proposal | → state | fields that change |",
        "| --- | --- | --- |",
        "| `Reset` | low [low] | — |",
        "",
        "## Blind spots",
        "",
        "### Untried proposals",
        "",
        "- `low`: `Inc`",
        "",
        "### Fields with one value in every explored state",
        "",
        "- `count`: `0`",
        ""
      ].join("\n")
    )
  })
})
